public class Week1_Basic_PersonalProfilePrinter {
    public static void main(String[] args) {
        // Declare at least 4 different primitive-type variables (e.g., int, double, char, boolean) representing age, height, initial, and student status. 
        // Initialize every variable at the moment of declaration.
        int age = 19;
        double height = 1.59;
        char initial = 'D';
        boolean studentstatus = true;

        // Declare at least 1 reference-type variable (a String) for your full name.
        // Initialize every variable at the moment of declaration.
        String fullname = "Ethan Ulrick D. Gueta";

        // Print all values on separate, clearly labeled lines.
        System.out.println("Full Name: " + fullname);
        System.out.println("Age: " + age);
        System.out.println("Height (m): " + height);
        System.out.println("Middle Initial: " + initial);
        System.out.println("Is a Student: " + studentstatus);
    }
}
